export function poolFor(name, category, role) {
  const text = `${name}${category}${role}`;
  if (/串|烤羊|烤肉|手抓|羊肉/.test(text)) return "lamb";
  if (/火锅/.test(text)) return "hotpot";
  if (/豆腐|豆花|豆脑/.test(text)) return "tofu";
  if (/鱼/.test(text)) return "fish";
  if (/面|粉|米线|拉面|拌面/.test(text)) return "noodle";
  if (/饭|抓饭|粥|炒饭/.test(text)) return "rice";
  if (/饺|包|馄饨|生煎|小笼/.test(text)) return "dumpling";
  if (/馕|饼|列巴|馍|面包/.test(text)) return "bread";
  if (/汤|奶茶|汁|茶|凉/.test(name) && role === "drink") return "drink";
  if (role === "drink") return "drink";
  if (role === "sweet") return "sweet";
  if (role === "soup") return "soup";
  if (role === "veg") return "veg";
  if (role === "staple") return "noodle";
  if (role === "meat") return "meat";
  return "chinese";
}
